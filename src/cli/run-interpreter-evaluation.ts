/**
 * Compares the rules interpreter with the optional model assisted interpreter
 * on the hand labelled messages in data/evaluation/interpreter-paraphrases.json.
 *
 * The rules interpreter always runs and its numbers are deterministic. The
 * model runs only when AFTERCARE_LLM_BASE_URL and AFTERCARE_LLM_MODEL are set.
 * With --write, the results are saved to data/evaluation/interpreter-results.json
 * and docs/INTERPRETER_EVALUATION.md, which requires a configured model so the
 * saved document always comes from a real run of both interpreters.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadConfig } from '../config.js';
import {
  evaluateInterpreter,
  FIELDS,
  loadParaphrases,
  type InterpreterRun,
} from '../evaluation/interpreter-evaluation.js';
import { interpreterFromConfig } from '../infrastructure/interpreter/llm-interpreter.js';
import { RulesInterpreter } from '../infrastructure/interpreter/rules-interpreter.js';

const jsonPath = fileURLToPath(
  new URL('../../data/evaluation/interpreter-results.json', import.meta.url),
);
const mdPath = fileURLToPath(new URL('../../docs/INTERPRETER_EVALUATION.md', import.meta.url));

const config = loadConfig();
const items = loadParaphrases();
const rules = new RulesInterpreter();

function print(run: InterpreterRun, label: string): void {
  console.info(`${label} (${run.interpreter})`);
  for (const f of FIELDS) console.info(`  ${f.padEnd(9)} ${run.correct[f]}/${items.length}`);
  console.info(`  all four ${run.allFieldsCorrect}/${items.length}`);
  if (run.fallbacks > 0) console.info(`  fell back to rules@1 on ${run.fallbacks} message(s)`);
}

const rulesRun = await evaluateInterpreter(rules, items);
console.info(`Messages: ${items.length}`);
print(rulesRun, 'Rules interpreter');

const assisted = interpreterFromConfig(config);
if (!assisted) {
  console.info(
    'No model configured (set AFTERCARE_LLM_BASE_URL and AFTERCARE_LLM_MODEL). Showing rules results only.',
  );
  if (process.argv.includes('--write')) {
    console.info('Nothing written: --write needs a configured model.');
  }
} else {
  const started = Date.now();
  const modelRun = await evaluateInterpreter(assisted, items, rules);
  const seconds = Math.round((Date.now() - started) / 100) / 10;
  print(modelRun, `Model assisted, model ${config.AFTERCARE_LLM_MODEL}`);
  console.info(`  took ${seconds} s for ${items.length} messages`);

  if (process.argv.includes('--write')) {
    const date = new Date().toISOString().slice(0, 10);
    const model = config.AFTERCARE_LLM_MODEL ?? '';
    writeFileSync(
      jsonPath,
      `${JSON.stringify({ date, messages: items.length, model, rules: rulesRun, modelAssisted: modelRun }, null, 2)}\n`,
    );
    writeFileSync(mdPath, render(date, model, seconds, rulesRun, modelRun));
    console.info(`Wrote ${jsonPath} and ${mdPath}`);
  }
}

function render(
  date: string,
  model: string,
  seconds: number,
  rulesRun: InterpreterRun,
  modelRun: InterpreterRun,
): string {
  const n = items.length;
  const addedReason = modelRun.items
    .filter((i) => i.missed.includes('reason'))
    .map((i) => i.id)
    .filter((id) => items.find((x) => x.id === id)?.expected.reason === null);
  const row = (label: string, run: InterpreterRun) =>
    `| ${label} | ${FIELDS.map((f) => `${run.correct[f]}/${n}`).join(' | ')} | ${run.allFieldsCorrect}/${n} |`;
  const misses = (run: InterpreterRun) =>
    run.items
      .filter((i) => i.missed.length > 0 || i.fallback)
      .map(
        (i) =>
          `| ${i.id} | ${i.missed.join(', ') || 'none'} | ${i.productQuery ?? 'null'} | ${i.fallback ?? ''} |`,
      )
      .join('\n');
  return `# Interpreter evaluation

Generated by \`npm run eval:interpreters -- --write\` on ${date}, with the model \`${model}\` served at ${new URL(config.AFTERCARE_LLM_BASE_URL ?? 'http://unknown').host} with a timeout of ${config.AFTERCARE_LLM_TIMEOUT_MS} ms. Rerun it to reproduce; the rules interpreter's numbers are deterministic, the model's may vary between runs and model versions.

${n} customer messages, labelled by hand before either interpreter was run on them (data/evaluation/interpreter-paraphrases.json). Each field is scored separately:

- **goal**: return, exchange or not stated.
- **reason**: defective, changed mind, or not stated.
- **product**: the extracted product query finds exactly the labelled order in the fictional sandbox (or no product is extracted when none is named).
- **time hint**: a purchase time is picked up when, and only when, the message states one.

Serial and order numbers are not scored: they always come from the rules interpreter. The model assisted reading takes the goal from the rules interpreter when it found one and from the model otherwise, accepts the model's reason only with a quote that appears in the message, uses the model for product, issue description and purchase time, and the rules interpreter for everything else. When the model fails (invalid output, HTTP error, timeout), the service uses the rules reading, and so does this score.

## Results

| Interpreter | goal | reason | product | time hint | all four |
| --- | --- | --- | --- | --- | --- |
${row('Rules (rules@1)', rulesRun)}
${row(`Model assisted (llm@1, ${model})`, modelRun)}

The model assisted interpreter fell back to the rules reading on ${modelRun.fallbacks} of ${n} messages. The model run took ${seconds} seconds in total on the machine used.

## Messages with at least one wrong field

Rules interpreter:

| Message | Wrong fields | Product query | Fallback |
| --- | --- | --- | --- |
${misses(rulesRun)}

Model assisted interpreter:

| Message | Wrong fields | Product query | Fallback |
| --- | --- | --- | --- |
${misses(modelRun)}

## Limitations

- ${n} messages, written and labelled by the same team that built the interpreters. They are a check of field extraction on plausible phrasings, not a measurement of real customer language.
- Some labels are judgement calls (for example, whether discomfort is a change of mind). They were fixed before any run and are not changed after.
- A reason is a customer claim, but it selects the policy rule, and so the shipping terms of the proposed return. In this run the model supplied a reason the customer did not state on ${addedReason.length} message(s)${addedReason.length > 0 ? ` (${addedReason.join(', ')})` : ''}. The proposed terms, including the reason, are shown to the customer before approval, but a wrong reason is still a real risk of using a model here.
- Better reading does not change what AFTERCARE may do. Every decision still comes from the compiler, and every identifier still comes from the customer's own text.
`;
}
